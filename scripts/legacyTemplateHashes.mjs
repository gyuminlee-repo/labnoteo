#!/usr/bin/env node
/**
 * Generate `src/scaffold/legacyTemplateHashes.ts`: for each file the setup
 * command installs, the hash of every template version a release up to
 * 0.95.0 shipped (#93).
 *
 * Vaults set up before 0.95.0 have no `.labnoteo/installed.json`, so plugin
 * load cannot tell an untouched file from an edited one by the record. A file
 * whose hash is one of these is an old release's template, untouched, and may
 * be refreshed. Every release since 0.82.0 embeds the templates verbatim (esbuild
 * `text` loader), so a tag's template file is what that release wrote.
 *
 * Releases from 0.95.0 on keep the record, so the list does not need to grow:
 * run once via `npm run gen:legacy-hashes` with the tags fetched.
 */
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const LAST = '0.95.0';
const OUT = join(root, 'src/scaffold/legacyTemplateHashes.ts');

/** Vault path → template under `automation/templates/`. */
const TEMPLATES = {
  'QUICKSTART.md': 'QUICKSTART.md',
  '.labnoteo/SETUP.md': 'SETUP.md',
  '.labnoteo/hooks/pre-commit': 'pre-commit.sh',
  '.github/workflows/validate.yml': 'validate.yml',
  '.github/workflows/experiment-issues.yml': 'experiment-issues.yml',
  '.github/workflows/wiki-sync.yml': 'wiki-sync.yml',
  '.github/ISSUE_TEMPLATE/experiment.md': 'experiment.md',
};

/** Same as `contentHash` in src/scaffold/installRecord.ts; the self-check test keeps them equal. */
function contentHash(text) {
  const s = text.replace(/\r\n/g, '\n');
  let h1 = 0xdeadbeef;
  let h2 = 0x41c6ce57;
  for (let i = 0; i < s.length; i++) {
    const ch = s.charCodeAt(i);
    h1 = Math.imul(h1 ^ ch, 2654435761);
    h2 = Math.imul(h2 ^ ch, 1597334677);
  }
  h1 = Math.imul(h1 ^ (h1 >>> 16), 2246822507) ^ Math.imul(h2 ^ (h2 >>> 13), 3266489909);
  h2 = Math.imul(h2 ^ (h2 >>> 16), 2246822507) ^ Math.imul(h1 ^ (h1 >>> 13), 3266489909);
  return (4294967296 * (2097151 & h2) + (h1 >>> 0)).toString(16).padStart(14, '0');
}

function parseVersion(tag) {
  const m = /^v?(\d+)\.(\d+)\.(\d+)$/.exec(tag);
  return m ? m.slice(1).map(Number) : undefined;
}

function compare(a, b) {
  for (let i = 0; i < 3; i++) if (a[i] !== b[i]) return a[i] - b[i];
  return 0;
}

function git(...args) {
  return execFileSync('git', args, { cwd: root, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
}

const last = parseVersion(LAST);
const tags = git('tag')
  .split('\n')
  .map(tag => ({ tag, version: parseVersion(tag.trim()) }))
  .filter(t => t.version && compare(t.version, last) <= 0)
  .sort((a, b) => compare(a.version, b.version));
if (!tags.some(t => compare(t.version, last) === 0)) {
  throw new Error(`Tag ${LAST} not found; fetch the tags first (git fetch --tags).`);
}

const hashes = {};
for (const [vaultPath, template] of Object.entries(TEMPLATES).sort(([a], [b]) => (a < b ? -1 : 1))) {
  const seen = new Set();
  for (const { tag } of tags) {
    let text;
    try {
      text = execFileSync('git', ['show', `${tag}:automation/templates/${template}`], {
        cwd: root,
        encoding: 'utf8',
        stdio: ['ignore', 'pipe', 'ignore'],
        maxBuffer: 64 * 1024 * 1024,
      });
    } catch {
      continue;
    }
    seen.add(contentHash(text));
  }
  hashes[vaultPath] = [...seen];
}

const sample = 'labnoteo self-check\r\n한글 템플릿 줄\n';
const body = Object.entries(hashes)
  .map(([path, list]) => `  '${path}': [\n${list.map(h => `    '${h}',`).join('\n')}\n  ],`)
  .join('\n');
const out = `// Generated by scripts/legacyTemplateHashes.mjs (npm run gen:legacy-hashes); do not edit.
// Template hashes of releases ${tags[0].tag} to ${LAST}, by vault path (#93).

export const LEGACY_TEMPLATE_HASHES: Readonly<Record<string, readonly string[]>> = {
${body}
};

/** A sample hashed by the generator, so a test can check it agrees with \`contentHash\`. */
export const LEGACY_HASH_SELF_CHECK = {
  text: '${sample.replace(/\r/g, '\\r').replace(/\n/g, '\\n')}',
  hash: '${contentHash(sample)}',
};
`;
writeFileSync(OUT, out);
console.log(`Wrote ${OUT} from ${tags.length} tags.`);
